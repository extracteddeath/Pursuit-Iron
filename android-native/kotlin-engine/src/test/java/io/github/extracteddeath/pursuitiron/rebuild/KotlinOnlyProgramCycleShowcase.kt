package io.github.extracteddeath.pursuitiron.rebuild

import java.math.BigDecimal
import java.nio.file.Files
import java.nio.file.Path

/**
 * Executable, reproducible Kotlin-only evidence. No JS engine is invoked.
 * Inputs are fictional athlete calibrations and gym stock, not real-user data.
 * Report only actual audited native outputs; never manufacture an example.
 */
object KotlinOnlyProgramCycleShowcase {
    @JvmStatic fun main(args:Array<String>) {
        require(args.size==1) {"Provide output Markdown path"}
        val out=StringBuilder()
        fun line(s:String="") {out.append(s).append('\n')}
        line("# Pursuit Iron — independently executed Kotlin programs and cycles")
        line()
        line("Generated by the Kotlin training engine from fictional athlete setup, confirmed equipment and explicit starting loads. No legacy JavaScript is executed, no web engine supplies prescriptions, and no workouts are issued.")
        line()
        val scenarios=listOf(
            ComposerSplit.FULL_BODY to TrainingPhase.HYPERTROPHY,
            ComposerSplit.UPPER_LOWER to TrainingPhase.HYPERTROPHY,
            ComposerSplit.ULPPL to TrainingPhase.STRENGTH,
            ComposerSplit.ULPPL to TrainingPhase.PEAK,
            ComposerSplit.PUSH_PULL_LEGS to TrainingPhase.PEAK
        )
        for((split,phase) in scenarios) {
            val request=StarterProgramReleaseFixture.request(split,phase)
            val review=CoachFirstProgramStartDomain.review(request)
            check(review.status==FirstProgramStartStatus.PRESCRIBED_DRAFT_FOR_REVIEW) {
                "Kotlin generation failed for $split / $phase: ${review.issues}"
            }
            val prescription=checkNotNull(review.prescription)
            check(checkNotNull(prescription.finalAudit).satisfiesDeclaredHardConstraints)
            check(checkNotNull(prescription.finalAudit).daysOutsidePreferredWindow.isEmpty())
            line("## $split — $phase")
            line()
            line("Policy: ${review.policy?.revision}; audited sessions: ${prescription.sessions.size}; phase candidates checked: ${review.phasePoliciesChecked}")
            line()
            for(session in prescription.sessions) {
                line("### Training day ${session.dayIndex+1} — ${session.estimatedMinutes} min")
                for(exercise in session.exercises) {
                    val work=exercise.sets.filter{it.type==DraftSetType.WORKING}
                    if(work.isEmpty())continue
                    val load=work.first().load
                    val loadLabel=when(load) {
                        is DraftSetLoad.Verified -> "${load.value.stripTrailingZeros().toPlainString()} ${load.unit}"
                        else -> "unverified"
                    }
                    line("- ${exercise.exerciseId}: ${work.size} working sets, ${work.first().targetReps}, target RIR ${work.first().targetRir}, $loadLabel")
                }
                line()
            }
            if(phase!=TrainingPhase.HYPERTROPHY) {
                val freq=review.generation?.candidate?.realization?.primaryFrequencies.orEmpty()
                line("Primary lift exposures: "+freq.joinToString("; ") {
                    "${it.exerciseId}: ${it.deliveredDays}/${it.requiredDays} days"
                })
                line()
            }
        }
        line("## Full-cycle Kotlin-only alternatives")
        line()
        // All three phase starts must belong to ONE reviewed athlete and gym.
        // A different athlete's hyper starter must never be smuggled in.
        val strength=StarterProgramReleaseFixture.request(
            ComposerSplit.ULPPL,TrainingPhase.STRENGTH)
        val hypertrophy=strength.copy(phase=TrainingPhase.HYPERTROPHY)
        val phases=TrainingPhase.entries.associateWith {phase->
            CoachFirstProgramStartDomain.review(
                if(phase==TrainingPhase.HYPERTROPHY)hypertrophy
                else strength.copy(phase=phase))
        }
        for((phase,review) in phases)check(
            review.status==FirstProgramStartStatus.PRESCRIBED_DRAFT_FOR_REVIEW) {
            "Missing independently prescribed $phase phase: ${review.issues}"
        }
        val cycle=CoachReviewedWholeCycleDomain.propose(
            ReviewedWholeCycleRequest(
                "kotlin-only-showcase","Independent nine-week powerbuilding",
                strength.setup,StarterExerciseTranche.movements(),
                phases,9,false,
                CustomCoachVolumeContinuityPolicy(
                    BigDecimal.ONE,BigDecimal.ONE,BigDecimal.ONE,BigDecimal.ONE)
            ))
        line("Status: ${cycle.status}; options: ${cycle.candidates.size}; recommended for review: ${cycle.initialReviewOptionId ?: "none"}")
        line()
        for(candidate in cycle.candidates) {
            line("- ${candidate.allocations.joinToString(" → "){"${it.first}: ${it.second} weeks"}} — ${candidate.status}; audited weeks: ${candidate.audit?.weeks?.size ?: 0}; proposed blocks: ${candidate.proposedCycle?.blocks?.size ?: 0}")
            if(candidate.status!=ReviewedWholeCycleCandidateStatus.READY_FOR_ATHLETE_REVIEW)
                line("  - Unresolved: ${candidate.explanation}")
        }
        check(cycle.candidates.any{it.audit?.weeks?.size==9 &&
            it.proposedCycle?.blocks?.size==2}) {
            "No actual nine-week two-block Kotlin cycle was generated and audited"
        }
        line()
        line("**Limits:** These are provisional reviewed drafts, not athlete-approved training plans. Calibrated starting loads are inputs, not predicted 1RMs. Full web parity, individualized fatigue accuracy, true peaking and beta approval remain unproven.")
        val path=Path.of(args[0]);Files.createDirectories(path.parent)
        Files.writeString(path,out.toString())
        println(out.toString())
    }
}
