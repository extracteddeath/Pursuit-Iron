/*
 * The M3 Expressive design's twelve colour themes. Each is one seed; light, dark and pure black all
 * come from it, so every theme works in every mode. The web app's light/dark twins are merged
 * (Citrus into Lime, Clay into Ember, Ochre into Gold, Sage into Emerald, Ice into Ocean, Slate into
 * Patrol, Lilac into Amethyst, Rosewater into Rose, Stone into Graphite); the old Teal and Violet map
 * to Mint and Amethyst.
 *
 * GENERATED from the design canvas (Main.dc.html palettes()) with material-color-utilities: primary
 * at the seed's hue and chroma (min 40; Forest held at 40, Graphite 0), secondary chroma 16, tertiary
 * at hue + 60 chroma 24, neutral 6, neutral-variant 8. The primary keeps the seed's own tone where
 * contrast allows (72–88 dark, 35–40 light). Every text/fill pair clears WCAG AA. Wallpaper is
 * Android 12+ dynamic colour; below that, and in the widget, it uses the design's sample scheme.
 */
enum class Seed(val label: String, val swatch: Long) {
    Wallpaper("Wallpaper", 0xFF7D5A80),
    Rose("Rose", 0xFFFF6B8A),
    Ember("Ember", 0xFFFF8A3D),
    Gold("Gold", 0xFFF5C542),
    Lime("Lime", 0xFFD4FF3D),
    Forest("Forest", 0xFFA8DC5D),
    Emerald("Emerald", 0xFF34D399),
    Mint("Mint", 0xFF238070),
    Ocean("Ocean", 0xFF0A6F8E),
    Patrol("Patrol", 0xFF2563EB),
    Amethyst("Amethyst", 0xFFB388FF),
    Graphite("Graphite", 0xFFD8D8DC);

    val isDynamic get() = this == Wallpaper

    companion object {
        private val ALIAS = mapOf("Teal" to Mint, "Violet" to Amethyst, "Citrus" to Lime, "Clay" to Ember, "Ochre" to Gold,
            "Sage" to Emerald, "Ice" to Ocean, "Slate" to Patrol, "Lilac" to Amethyst, "Rosewater" to Rose, "Stone" to Graphite)
        fun from(name: String?): Seed = entries.firstOrNull { it.name == name } ?: ALIAS[name] ?: Ember
        val dynamicSupported get() = Build.VERSION.SDK_INT >= Build.VERSION_CODES.S
    }
}

/** The scheme for a theme. Pass a [context] to get real wallpaper colours for [Seed.Wallpaper] on Android 12+. */
fun schemeFor(seed: Seed, dark: Boolean, black: Boolean = false, context: Context? = null): ColorScheme {
    val base = if (seed.isDynamic && context != null && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
        if (dark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
    } else {
        val p = PALETTES.getValue(seed)
        if (dark) p.dark else p.light
    }
    if (!dark || !black) return base
    val b = PALETTES.getValue(seed).black
    return if (seed.isDynamic && context != null && Seed.dynamicSupported) {
        // Wallpaper colours: keep the device's tints, pull every surface down toward black.
        base.copy(background = Color.Black, surface = Color.Black, surfaceDim = Color.Black, surfaceContainerLowest = Color.Black,
            surfaceContainerLow = lerp(base.surfaceContainerLow, Color.Black, 0.6f), surfaceContainer = lerp(base.surfaceContainer, Color.Black, 0.55f),
            surfaceContainerHigh = lerp(base.surfaceContainerHigh, Color.Black, 0.45f), surfaceContainerHighest = lerp(base.surfaceContainerHighest, Color.Black, 0.35f),
            surfaceVariant = lerp(base.surfaceVariant, Color.Black, 0.35f))
    } else base.copy(background = b.background, surface = b.surface, surfaceDim = b.surfaceDim, surfaceContainerLowest = b.surfaceContainerLowest,
        surfaceContainerLow = b.surfaceContainerLow, surfaceContainer = b.surfaceContainer, surfaceContainerHigh = b.surfaceContainerHigh,
        surfaceContainerHighest = b.surfaceContainerHighest, surfaceVariant = b.surfaceVariant, surfaceBright = b.surfaceBright)
}

/** The three colours a theme picker swatch shows: primary on top, tertiary and secondary containers below. */
data class Swatch(val top: Color, val left: Color, val right: Color)
fun swatchFor(seed: Seed, dark: Boolean, context: Context? = null): Swatch {
    val s = schemeFor(seed, dark, false, context)
    return Swatch(s.primary, s.tertiaryContainer, s.secondaryContainer)
}

