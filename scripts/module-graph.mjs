import fs from 'node:fs';
import path from 'node:path';

// The app ships unbundled ES modules. Without hints the browser discovers them one import level
// at a time: main.js -> App.js -> its imports -> ... 14 levels deep, each a separate round trip
// before the next level is even requested. index.html lists the whole static graph as
// <link rel="modulepreload"> so every module is fetched and compiled in parallel.
// Dynamic import() targets stay lazy and are not listed.
export const PRELOAD_START = '<!-- modulepreload:start (generated by scripts/finalize-release.mjs) -->';
export const PRELOAD_END = '<!-- modulepreload:end -->';

const STATIC_IMPORT = /(?:^|[;}\n])\s*(?:import|export)\s+(?:[\w*{}\s,$]*?\s+from\s+)?['"]([^'"\n]+)['"]/g;

export function importMap(indexHtml) {
    const match = indexHtml.match(/<script type="importmap">([\s\S]*?)<\/script>/);
    if (!match) throw new Error('index.html has no import map');
    return JSON.parse(match[1]).imports || {};
}

export function staticModuleGraph(indexHtml, entry = 'modules/main.js') {
    const imports = importMap(indexHtml);
    const seen = [];
    const visit = file => {
        if (seen.includes(file)) return;
        if (!fs.existsSync(file)) throw new Error('Static import target missing: ' + file);
        seen.push(file);
        const source = fs.readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
        for (const [, specifier] of source.matchAll(STATIC_IMPORT)) {
            if (specifier.startsWith('.')) visit(path.posix.normalize(path.posix.join(path.posix.dirname(file), specifier)));
            else if (imports[specifier]) visit(path.posix.normalize(imports[specifier]));
            else throw new Error(`Unmapped bare import "${specifier}" in ${file}`);
        }
    };
    visit(entry);
    return seen;
}

export function preloadBlock(indexHtml) {
    const links = staticModuleGraph(indexHtml).map(file => `    <link rel="modulepreload" href="./${file}">`);
    return [`    ${PRELOAD_START}`, ...links, `    ${PRELOAD_END}`].join('\n');
}

// Replace (or insert, right after the import map) the generated block.
export function withPreloads(indexHtml) {
    const block = preloadBlock(indexHtml);
    const start = indexHtml.indexOf('    ' + PRELOAD_START);
    if (start >= 0) {
        const end = indexHtml.indexOf(PRELOAD_END, start) + PRELOAD_END.length;
        return indexHtml.slice(0, start) + block + indexHtml.slice(end);
    }
    const anchor = indexHtml.indexOf('</script>', indexHtml.indexOf('<script type="importmap">')) + '</script>'.length;
    return indexHtml.slice(0, anchor) + '\n' + block + indexHtml.slice(anchor);
}
