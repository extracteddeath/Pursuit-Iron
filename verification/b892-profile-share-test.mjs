import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const app=fs.readFileSync(new URL("../modules/App.js",import.meta.url),"utf8");
const css=fs.readFileSync(new URL("../app.css",import.meta.url),"utf8");
const start=app.indexOf("const PROFILE_LAYOUT_CHOICES =");
const end=app.indexOf("function ProfileCustomization(",start);
assert.ok(start>0&&end>start,"Profile preference model must exist");
const pure=app.slice(start,end);
const context={};
vm.runInNewContext(pure+"\nthis.normalize = normalizeProfilePrefs;",context);
const read=x=>JSON.parse(JSON.stringify(context.normalize(x)));
const defaults=read(null);
assert.deepEqual(defaults.order,["level","summary","strength","club","achievements"]);
assert.deepEqual(defaults.hidden,[]);
assert.deepEqual(defaults.share,["strength","streak"]);
const restored=read({order:["prs","achievements","achievements","club","level"],hidden:["summary","bogus"],share:["prs","club","prs"]});
assert.deepEqual(restored.order,["achievements","club","level","summary","strength"],"Only Profile sections may be ordered, not share-only PRs");
assert.deepEqual(restored.hidden,["summary"]);
assert.deepEqual(restored.share,["prs","club"]);
const damaged=read({order:["summary"],hidden:["level","summary","strength","club","achievements"],share:[]});
assert.ok(damaged.order.includes("achievements"));
assert.ok(damaged.hidden.length<5,"Never show an empty Profile");
assert.ok(damaged.share.length>0,"Never create a blank share image");
assert.match(app,/localStorage\.setItem\(PROFILE_PREFERENCE_KEY, JSON\.stringify\(safe\)\)/);
assert.match(app,/function shareCustomProfileCard\(\{ history, unit, score, level, milestones, prefs, theme \}\)/);
assert.match(app,/\bstrengthClubSnapshot\(exerciseTrends\(history\), unit, "lifted"\)/);
assert.match(app,/\bliftBests\(history \|\| \[\], unit\)/);
assert.match(app,/\.\.\.profilePrefs\.order\.filter\(id => !profilePrefs\.hidden\.includes\(id\)\)/);
assert.match(app,/showProfileCustomize && _jsx\(ProfileCustomization/);
assert.match(app,/"aria-pressed": selected/);
assert.match(app,/Share profile/);
assert.match(css,/\.wpb-profile-toolbar/);
assert.match(css,/\.wpb-profile-customize-row/);
assert.match(css,/@media\(max-width:350px\)/);
assert.equal(read({cardName: "A".repeat(80)}).cardName.length,60);
assert.deepEqual(read({favorites:["bench","bench","squat","deadlift","curl",null]}).favorites,["bench","squat","deadlift"]);
assert.deepEqual(read({share:["streak","favorites","unknown"]}).share,["streak","favorites"]);
assert.equal(read(null).cardName,"");
assert.match(app,/function profileCardRows/);
assert.match(app,/const rows = profileCardRows\(\{ history, unit, score, level, milestones, prefs \}\)/);
assert.match(app,/prefs.cardName.trim\(\) \|\| "My training"/);
console.log("PASS B892: Profile preference normalization, section ordering, share metrics and responsive controls.");
